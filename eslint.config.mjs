// @ts-check
// ESLint here exists for the Tailwind guard rails from "Tailwind Utilities":
// classes in markup must be registered Tailwind utilities (built-in,
// generated from @theme tokens, or declared with @utility), and arbitrary
// values are banned.
//
// No typescript-eslint: the project is on TypeScript 7, whose npm package
// exposes no JS compiler API, and typescript-eslint (peer typescript <6.1)
// can't run without it. TypeScript *syntax* is parsed by Babel instead, so
// the Tailwind rules, core rules and react-hooks still run; type-aware and
// TS-specific rules are left to the TypeScript compiler.
import babelParser from "@babel/eslint-parser";
import js from "@eslint/js";
import * as astroParser from "astro-eslint-parser";
import betterTailwindcss from "eslint-plugin-better-tailwindcss";
import { getDefaultSelectors } from "eslint-plugin-better-tailwindcss/defaults";
import reactHooks from "eslint-plugin-react-hooks";
import { defineConfig, globalIgnores } from "eslint/config";
import globals from "globals";

/** Babel options that parse TypeScript (and JSX) without the TS compiler. */
const babelTs = (/** @type {{ jsx?: boolean }} */ { jsx = false } = {}) => ({
  requireConfigFile: false,
  babelOptions: {
    babelrc: false,
    configFile: false,
    // Syntax only: no transform runs, so no preset is needed. JSX stays off
    // for .ts, where it would misread `<T>value` casts.
    parserOpts: { plugins: jsx ? ["typescript", "jsx"] : ["typescript"] },
  },
});

// Core scope analysis sees neither type positions nor components used as
// JSX/Astro tags, so these two rules misfire on nearly every import here
// (~115 false hits). The compiler checks both (noUnusedLocals, and
// unresolved names are type errors).
const tsSyntaxRules = {
  "no-undef": "off",
  "no-unused-vars": "off",
};

export default defineConfig(
  globalIgnores([
    "dist/",
    ".astro/",
    "public/",
    "node_modules/",
    ".wrangler/",
    ".venv/",
    // Generated by `npm run docs:generate`.
    "src/content/docs/docs/*/reference/",
  ]),

  js.configs.recommended,
  { rules: { curly: ["error", "all"] } },

  {
    files: ["**/*.{ts,mts,cts}"],
    languageOptions: { parser: babelParser, parserOptions: babelTs() },
    rules: tsSyntaxRules,
  },

  {
    files: ["**/*.tsx"],
    languageOptions: {
      parser: babelParser,
      parserOptions: babelTs({ jsx: true }),
      globals: globals.browser,
    },
    rules: tsSyntaxRules,
  },

  {
    files: ["**/*.astro"],
    languageOptions: {
      parser: astroParser,
      parserOptions: {
        parser: babelParser,
        ...babelTs({ jsx: true }),
        extraFileExtensions: [".astro"],
        sourceType: "module",
      },
      globals: { ...globals.browser, ...globals.node },
    },
    rules: tsSyntaxRules,
  },

  {
    files: ["**/*.{tsx,jsx}"],
    extends: [reactHooks.configs.flat["recommended-latest"]],
  },

  {
    files: ["**/*.{js,mjs,cjs}"],
    languageOptions: { globals: globals.node },
  },

  // Tailwind guard rails.
  {
    files: ["**/*.{astro,tsx,jsx,ts}"],
    plugins: { "better-tailwindcss": betterTailwindcss },
    settings: {
      "better-tailwindcss": {
        // Tailwind v4 has no JS config; the plugin reads the theme, tokens
        // and @utility declarations from the stylesheet that imports it.
        entryPoint: "src/styles/custom.css",
        // Keep false: true would accept every class *defined* in the CSS,
        // i.e. exactly the invented class names the rule is meant to stop.
        detectComponentClasses: false,
        // By default only class/className/class:list attributes and variables
        // named classNames?/classes/styles? are read. Class strings kept
        // anywhere else are unchecked unless listed here.
        selectors: [
          ...getDefaultSelectors(),
          {
            kind: "variable",
            name: "^textures$",
            match: [{ type: "objectValues", path: String.raw`^\[\d+\]\.cssClass$` }],
          },
        ],
      },
    },
    rules: {
      "better-tailwindcss/no-unknown-classes": ["error", { ignore: [] }],
      "better-tailwindcss/no-restricted-classes": [
        "error",
        {
          // A bracket group at the end of the class (before an optional
          // /modifier and ! suffix) is an arbitrary value: w-[37px],
          // md:bg-[url(x)], bg-gray-3/[0.5], [mask-type:alpha]. A bracket
          // starting a variant is an arbitrary variant: [&>p]:mt-2.
          // Bracketed *named* variants stay allowed: data-[state=open]:,
          // aria-[sort=ascending]:, supports-[display:grid]:. A bare "\[" or
          // "-\[" would also flag those.
          restrict: [
            {
              pattern: String.raw`\[[^\]]*\](?:/\S*)?!?$`,
              message:
                "Arbitrary value: name it as an @theme token or add an @utility instead.",
            },
            {
              pattern: String.raw`(?:^|:)!?\[`,
              message:
                "Arbitrary property or variant: add an @utility or @custom-variant instead.",
            },
          ],
        },
      ],
    },
  },
);
